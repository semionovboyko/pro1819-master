package _02ejemplos;

public class _09ClaseMath {
	public static void main(String[] args) {
		
		System.out.println("20 elevado a 4: " + Math.pow(20, 4));
		System.out.println("Raiz de 165: " + Math.sqrt(165));
		System.out.println("Ceil de 12.25: " + Math.ceil(12.25));
		System.out.println("Floor de 12.25: " + Math.floor(12.25));
		System.out.println("Redondeo de 12.25: " + Math.round(12.25));
		
		System.out.println("---------------------");
		System.out.println("Numero al azar: " + Math.random());
		
	}
}
