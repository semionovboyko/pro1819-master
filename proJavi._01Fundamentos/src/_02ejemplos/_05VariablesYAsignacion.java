package _02ejemplos;

public class _05VariablesYAsignacion {
	public static void main(String[] args){
		
		//Declaramos variable, le asignamos valor y la mostramos
		int edadMiguel;
		edadMiguel = 10;
		System.out.println("Edad de Miguel: " + edadMiguel);

		//La variable solo acepta valores enteros
		edadMiguel = 30;
		edadMiguel = 213 * 123;
		edadMiguel = 158 / 2;
		
		//edadMiguel = 12.5; //No se puede asignar un numero real
		
	}
}
